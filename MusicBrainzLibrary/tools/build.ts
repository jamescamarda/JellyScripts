const output = "SorseeLoved.user.js";
const temp = await Deno.makeTempFile({ suffix: ".js" });
try {
  const result = await new Deno.Command(Deno.execPath(), {
    args: [
      "bundle",
      "--platform=browser",
      "--format=iife",
      "--output",
      temp,
      "src/coordinator.ts",
    ],
    stdout: "inherit",
    stderr: "inherit",
  }).output();
  if (!result.success) throw new Error("Userscript bundle failed");
  const header = `// ==UserScript==
// @name         Sorsee Loved enrichment
// @namespace    https://github.com/jamescamarda/JellyScripts
// @version      2026.11.09.1
// @description  Enrich Loved recordings using String Theory with strict digital-edition matching.
// @match        https://musicbrainz.org/*
// @run-at       document-end
// @inject-into  page
// @noframes
// @grant        unsafeWindow
// @grant        GM.getValue
// @grant        GM.setValue
// @grant        GM.deleteValue
// @grant        GM.listValues
// @grant        GM_openInTab
// @grant        GM_registerMenuCommand
// @grant        GM_removeValueChangeListener
// @grant        GM_addValueChangeListener
// ==/UserScript==
// Generated by deno task build; edit the TypeScript sources, then rebuild.
`;
  await Deno.writeTextFile(output, header + await Deno.readTextFile(temp));
  console.log(`Built ${output}`);
} finally {
  await Deno.remove(temp);
}
